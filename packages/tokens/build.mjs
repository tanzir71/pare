// Turns design/tokens.json into:
//   dist/tokens.css  — CSS variables (--pare-<path>): :root = light, [data-theme=dark] = dark,
//                      plus [data-theme=system] following prefers-color-scheme.
//   dist/theme.css   — a Tailwind v4 `@theme inline` block mapping utilities onto those variables.
//   dist/tokens.json — a flat { name: { light, dark } } map for code that needs values (e.g. canvas).
// `node build.mjs --check` fails if dist/ is out of date (used in CI).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../design/tokens.json");
const out = resolve(here, "dist");
const tokens = JSON.parse(readFileSync(src, "utf8"));

/** Flatten color tokens into [name, light, dark]. Brand tokens are single-valued. */
export function flattenColors(node, path = []) {
  const rows = [];
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (value && typeof value === "object" && "light" in value && "dark" in value) {
      rows.push([[...path, key].join("-"), value.light, value.dark]);
    } else if (value && typeof value === "object") {
      rows.push(...flattenColors(value, [...path, key]));
    } else if (typeof value === "string" && value.startsWith("#")) {
      rows.push([[...path, key].join("-"), value, value]);
    }
  }
  return rows;
}

const colors = flattenColors(tokens.color);
const px = (n) => (n === 999 ? "9999px" : `${n}px`);
const header = "/* Generated by packages/tokens/build.mjs from design/tokens.json. Do not edit. */\n";

function lightBlock() {
  const lines = [];
  for (const [name, light] of colors) lines.push(`  --pare-${name}: ${light};`);
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(`  --pare-radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(tokens.space)) lines.push(`  --pare-space-${k}: ${px(v)};`);
  lines.push(`  --pare-font-sans: ${tokens.font.family.sans};`);
  lines.push(`  --pare-font-mono: ${tokens.font.family.mono};`);
  for (const [k, s] of Object.entries(tokens.font.style)) {
    lines.push(`  --pare-type-${k}-size: ${px(s.size)};`);
    lines.push(`  --pare-type-${k}-line: ${px(s.line)};`);
    lines.push(`  --pare-type-${k}-weight: ${s.weight};`);
    lines.push(`  --pare-type-${k}-tracking: ${s.tracking === "0" ? "0em" : s.tracking};`);
  }
  for (const [k, v] of Object.entries(tokens.shadow)) lines.push(`  --pare-shadow-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.motion)) lines.push(`  --pare-motion-${k}: ${v};`);
  lines.push("  color-scheme: light;");
  return lines.join("\n");
}

function darkBlock(indent = "  ") {
  const lines = colors
    .filter(([, l, d]) => l !== d)
    .map(([name, , dark]) => `${indent}--pare-${name}: ${dark};`);
  lines.push(`${indent}color-scheme: dark;`);
  return lines.join("\n");
}

export function buildTokensCss() {
  return (
    header +
    `:root {\n${lightBlock()}\n}\n\n` +
    `[data-theme="dark"] {\n${darkBlock()}\n}\n\n` +
    `@media (prefers-color-scheme: dark) {\n  [data-theme="system"] {\n${darkBlock("    ")}\n  }\n}\n`
  );
}

export function buildThemeCss() {
  const lines = [];
  // Drop Tailwind's default palette so only token colors exist (no raw hex in components).
  lines.push("  --color-*: initial;");
  lines.push("  --color-white: var(--pare-text-on-accent);");
  for (const [name] of colors) {
    if (name.startsWith("brand-")) continue;
    lines.push(`  --color-${name}: var(--pare-${name});`);
  }
  lines.push("  --radius-*: initial;");
  for (const k of Object.keys(tokens.radius)) lines.push(`  --radius-${k}: var(--pare-radius-${k});`);
  lines.push("  --font-sans: var(--pare-font-sans);");
  lines.push("  --font-mono: var(--pare-font-mono);");
  for (const k of Object.keys(tokens.font.style)) {
    lines.push(`  --text-${k}: var(--pare-type-${k}-size);`);
    lines.push(`  --text-${k}--line-height: var(--pare-type-${k}-line);`);
    lines.push(`  --text-${k}--letter-spacing: var(--pare-type-${k}-tracking);`);
    lines.push(`  --text-${k}--font-weight: var(--pare-type-${k}-weight);`);
  }
  lines.push("  --shadow-*: initial;");
  for (const k of Object.keys(tokens.shadow)) lines.push(`  --shadow-${k}: var(--pare-shadow-${k});`);
  lines.push(`  --ease-pare: var(--pare-motion-ease);`);
  return (
    header +
    `/* Import after "tailwindcss" and tokens.css. */\n@theme inline {\n${lines.join("\n")}\n}\n\n` +
    `@utility overline {\n  text-transform: uppercase;\n}\n`
  );
}

export function buildJson() {
  const flat = {};
  for (const [name, light, dark] of colors) flat[name] = { light, dark };
  return JSON.stringify({ color: flat, radius: tokens.radius, space: tokens.space }, null, 2) + "\n";
}

const outputs = {
  "tokens.css": buildTokensCss(),
  "theme.css": buildThemeCss(),
  "tokens.json": buildJson(),
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = [];
    for (const [file, content] of Object.entries(outputs)) {
      let current = "";
      try {
        current = readFileSync(resolve(out, file), "utf8");
      } catch {
        /* missing */
      }
      if (current.replace(/\r\n/g, "\n") !== content) stale.push(file);
    }
    if (stale.length) {
      console.error(`tokens: dist is out of date (${stale.join(", ")}). Run "pnpm tokens".`);
      process.exit(1);
    }
    console.log("tokens: dist is up to date");
  } else {
    mkdirSync(out, { recursive: true });
    for (const [file, content] of Object.entries(outputs)) writeFileSync(resolve(out, file), content);
    console.log(`tokens: wrote ${Object.keys(outputs).join(", ")} (${colors.length} colors)`);
  }
}
